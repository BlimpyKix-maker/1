function eraNote(y) {
  if (y < 1930) return 'Made at the turn from silence to sound; a version with title cards was prepared just in case.';
  if (y < 1950) return 'Made under the studio system: the cast and crew were on contract, and the studio owned the cinemas it played in.';
  if (y < 1968) return 'Made under the old production code, which explains the twin beds and the fade-outs.';
  if (y < 1980) return 'Made in the years when directors had the final cut and studios were too nervous to argue.';
  if (y < 1995) return 'Released when home video was turning flops into hits two years later.';
  if (y < 2008) return 'One of the last films of its kind to be cut on film, by hand, on a flatbed.';
  if (y < 2018) return 'Made as the business moved to digital projection; the last film prints were struck that year.';
  return 'Made in the streaming era, and still released in cinemas, which was the fight.';
}
