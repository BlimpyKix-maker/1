function extraFilmTrivia(f) {
  if (f.real) return [];
  const r = hashRand(f.id * 6151 + 29), lead = f.cast[0] !== undefined && P(f.cast[0]) ? P(f.cast[0]).name : 'The lead', d = P(f.dir) ? P(f.dir).name : 'The director', fill = t => t.replace(/\{lead\}/g, lead).replace(/\{dir\}/g, d), out = [];
  const G = GENRE_NOTES[f.genre]; if (G) out.push(['f', fill(G[Math.floor(r() * G.length)]), 6]);
  if (f.rel !== null && r() < .6) out.push(['f', eraNote(yearOf(f.rel)), 4]);
  if (f.rel !== null && r() < .7) out.push(['r', fill(RUMOURS_FILM[Math.floor(r() * RUMOURS_FILM.length)]), 18]);
  return out;
}
function extraPersonTrivia(p) {
  const r = hashRand(p.id * 2741 + 31), out = [], J = JOB_NOTES[p.role];
  if (J && !p.catId) out.push(['f', J[Math.floor(r() * J.length)], 9]);
  if (p.role === 'director' && typeof shortsBy === 'function') for (const s of shortsBy(p.id).slice(0, 2)) out.push(['f', `Before features: ${s.title}, a short that ${s.won ? 'won the ' + SHORT_FEST[s.fk].prize + ' at' : 'played'} ${SHORT_FEST[s.fk].name} in ${s.y}.`, 3]);
  if (!p.catId && p.standing > 10 && r() < .6) out.push(['r', RUMOURS_PERSON[Math.floor(r() * RUMOURS_PERSON.length)], 17]);
  return out;
}
